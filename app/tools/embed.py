"""Embed the Pico firmware files into src/firmware_files.h for the app's installer."""
import os, sys
root = os.path.join(os.path.dirname(__file__), "..", "..", "firmware")
files = ["main.py", "lib/usb/device/__init__.py", "lib/usb/device/core.py",
         "lib/usb/device/hid.py", "lib/usb/device/mouse.py"]
out = ["// Generated by tools/embed.py - do not edit.", "#pragma once", "#include <cstddef>", "",
       "struct EmbeddedFile { const char* path; const unsigned char* data; size_t size; };", ""]
for i, f in enumerate(files):
    data = open(os.path.join(root, f), "rb").read()
    out.append("static const unsigned char kFw%d[] = {" % i)
    for j in range(0, len(data), 24):
        out.append("    " + ",".join(str(b) for b in data[j:j + 24]) + ",")
    out.append("};")
out.append("static const EmbeddedFile kFirmwareFiles[] = {")
for i, f in enumerate(files):
    out.append('    {"%s", kFw%d, sizeof(kFw%d)},' % (f, i, i))
out.append("};")
out.append("static const int kFirmwareFileCount = %d;" % len(files))
ver = [l for l in open(os.path.join(root, "main.py")) if l.startswith("VERSION")][0].split('"')[1]
out.append('static const char* kFirmwareVersion = "%s";' % ver)
open(os.path.join(os.path.dirname(__file__), "..", "src", "firmware_files.h"), "w").write("\n".join(out) + "\n")
print("embedded", len(files), "files, version", ver)
